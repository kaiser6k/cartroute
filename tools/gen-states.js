#!/usr/bin/env node
/* Generates ../states.js (compact 50-state + DC table) from tools/state-rules.json (research) and
   tools/us-states.geojson (public-domain-ish state outlines, PublicaMundi/MappingAPI). Run: node tools/gen-states.js */
'use strict';
const fs = require('fs'), path = require('path');
const rules = JSON.parse(fs.readFileSync(path.join(__dirname, 'state-rules.json'), 'utf8'));
const geo = JSON.parse(fs.readFileSync(path.join(__dirname, 'us-states.geojson'), 'utf8'));
const VERIFIED = { FL: true };           // only Florida is statute-verified
const TOL = 0.04;                         // simplification tolerance in degrees (~4 km)
const MIN_RING_SPAN = 0.12;               // drop tiny islands

function dp(pts, tol) { // Douglas-Peucker
  if (pts.length < 3) return pts;
  const keep = new Array(pts.length).fill(false); keep[0] = keep[pts.length - 1] = true;
  const st = [[0, pts.length - 1]];
  while (st.length) {
    const [a, b] = st.pop(); let md = 0, mi = -1;
    for (let i = a + 1; i < b; i++) {
      const [x, y] = pts[i], [x1, y1] = pts[a], [x2, y2] = pts[b];
      const dx = x2 - x1, dy = y2 - y1, l2 = dx * dx + dy * dy;
      let t = l2 ? ((x - x1) * dx + (y - y1) * dy) / l2 : 0; t = Math.max(0, Math.min(1, t));
      const d = Math.hypot(x - (x1 + t * dx), y - (y1 + t * dy));
      if (d > md) { md = d; mi = i; }
    }
    if (md > tol && mi > 0) { keep[mi] = true; st.push([a, mi], [mi, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
const r2 = n => Math.round(n * 100) / 100;
function srcHost(u) { try { return new URL(u).hostname.toLowerCase(); } catch (e) { return ''; } }
const BAD = /cityrulelookup|legislative\.observer|laws9|getpocketlaw|lawserver|findlaw|justia|public\.law|elaws\.us|afdc\.energy|iml\.org|zendesk/;
function official(u, ab) {
  const h = srcHost(u);
  if (BAD.test(h)) return false;
  if (h === 'www.cga.ct.gov' && ab !== 'CT') return false;
  if (h === 'www.ltrc.la.gov' && ab !== 'LA') return false;
  return /\.gov$|\.us$|\.net$|legislature|\.state\./.test(h) || /mainelegislature\.org/.test(h);
}
function stateLaw(s) { return s.sources.find(u => official(u, s.abbr)) || s.sources[0] || ''; }
function dmvLink(s) { return s.sources.find(u => /dmv\.|mva\.|\/mvc\/|dps\.|dor\.sd|dot\.state\.wy|dmv\.nv|scdps|flhsmv/.test(u) && official(u, s.abbr)) || ''; }
function lsvLimit(v) {
  if (typeof v === 'number') return v;
  const m = /^(\d{2})\s*\(/.exec(String(v || '')); // e.g. "35 (not read from statute; secondary)"
  return m ? +m[1] : 35;                          // unknown / local option / not allowed -> default 35
}
const byName = {}; geo.features.forEach(f => { byName[f.properties.name] = f; });
const out = [];
rules.forEach(s => {
  const f = byName[s.state === 'District of Columbia' ? 'District of Columbia' : s.state];
  if (!f) throw new Error('no outline for ' + s.state);
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const rings = [];
  polys.forEach(p => { const ring = p[0], xs = ring.map(c => c[0]), ys = ring.map(c => c[1]);
    if (Math.max(...xs) - Math.min(...xs) < MIN_RING_SPAN && Math.max(...ys) - Math.min(...ys) < MIN_RING_SPAN && polys.length > 1) return;
    const sp = dp(ring, TOL); if (sp.length < 4) return;
    rings.push(sp.map(c => [r2(c[0]), r2(c[1])]).reduce((a, c) => a.concat(c), [])); });
  if (s.abbr === 'FL') rings.push([-82.0, 24.4, -81.0, 24.65, -80.3, 25.05, -80.2, 25.35, -80.45, 25.35, -81.1, 25.0, -82.0, 24.75]); // Florida Keys (missing from the outline source)
  const all = rings.reduce((a, r) => a.concat(r), []); const lons = all.filter((_, i) => i % 2 === 0), lats = all.filter((_, i) => i % 2 === 1);
  const b = [Math.min(...lats), Math.max(...lats), Math.min(...lons), Math.max(...lons)].map(r2);
  out.push({ n: s.state, a: s.abbr, l: lsvLimit(s.lsvMaxRoadMph), v: !!VERIFIED[s.abbr], u: stateLaw(s), d: dmvLink(s), b, c: [r2((b[0] + b[1]) / 2), r2((b[2] + b[3]) / 2)], p: rings });
});
const body = `/* ===== CartRoute state table + detection (pure JS). GENERATED by tools/gen-states.js from tools/state-rules.json: do not edit by hand. ===== */
var ST = (function () {
  'use strict';
  // n name, a abbr, l LSV max road mph (default 35 when unknown), v verified flag (only FL), u state-law link, d state DMV link ('' = none verified),
  // b bbox [s,n,w,e], c centroid [lat,lon], p outline rings as flat [lon,lat,...] (coarse, about 4 km)
  var T = ${JSON.stringify(out)};
  // US coverage check: contiguous US, Alaska, Hawaii (rough boxes; include some water and sliver of Canada/Mexico)
  var US_BOXES = [[24.3, 49.5, -125.2, -66.8], [51.0, 71.6, -180, -129.5], [18.7, 22.5, -160.6, -154.6]];
  function inUS(lat, lon) {
    if (!isFinite(lat) || !isFinite(lon)) return false;
    return US_BOXES.some(function (b) { return lat >= b[0] && lat <= b[1] && lon >= b[2] && lon <= b[3]; });
  }
  function inRing(lat, lon, r) {
    var c = false;
    for (var i = 0, j = r.length - 2; i < r.length; j = i, i += 2) {
      var xi = r[i], yi = r[i + 1], xj = r[j], yj = r[j + 1];
      if ((yi > lat) !== (yj > lat) && lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) c = !c;
    }
    return c;
  }
  function ringDist(lat, lon, r) { // approx distance (deg) to the nearest outline segment
    var m = 1e9, k = Math.cos(lat * Math.PI / 180);
    for (var i = 0, j = r.length - 2; i < r.length; j = i, i += 2) {
      var ax = r[j] * k, ay = r[j + 1], bx = r[i] * k, by = r[i + 1], px = lon * k, dx = bx - ax, dy = by - ay, l2 = dx * dx + dy * dy;
      var t = l2 ? ((px - ax) * dx + (lat - ay) * dy) / l2 : 0; t = t < 0 ? 0 : t > 1 ? 1 : t;
      var d = Math.hypot(px - (ax + t * dx), lat - (ay + t * dy)); if (d < m) m = d;
    }
    return m;
  }
  // State row for a point, or null. Point-in-outline first (bbox pre-check); coastal/water points fall back to the
  // nearest outline within ~0.5 degrees (ties broken by nearest centroid).
  function detect(lat, lon) {
    if (!inUS(lat, lon)) return null;
    var i, k, t;
    for (i = 0; i < T.length; i++) { t = T[i];
      if (lat < t.b[0] || lat > t.b[1] || lon < t.b[2] || lon > t.b[3]) continue;
      for (k = 0; k < t.p.length; k++) if (inRing(lat, lon, t.p[k])) return t; }
    var best = null, bd = 0.5;
    for (i = 0; i < T.length; i++) { t = T[i]; var d = 1e9;
      for (k = 0; k < t.p.length; k++) d = Math.min(d, ringDist(lat, lon, t.p[k]));
      if (d < bd - 1e-9 || (best && Math.abs(d - bd) < 1e-9 && Math.hypot(lat - t.c[0], lon - t.c[1]) < Math.hypot(lat - best.c[0], lon - best.c[1]))) { bd = d; best = t; } }
    return best;
  }
  function get(ab) { ab = String(ab || '').toUpperCase(); for (var i = 0; i < T.length; i++) if (T[i].a === ab) return T[i]; return null; }
  function lsvLimit(ab) { var t = get(ab); return t ? t.l : 35; }
  function isVerified(ab) { var t = get(ab); return !!(t && t.v); }
  function search(t) { return 'https://www.google.com/search?q=' + encodeURIComponent(t.n + ' golf cart low speed vehicle laws'); }
  function lawLink(t) { return t.u || search(t); }
  function dmvLink(t) { return t.d || 'https://www.google.com/search?q=' + encodeURIComponent(t.n + ' DMV low speed vehicle registration'); }
  return { T: T, US_BOXES: US_BOXES, inUS: inUS, detect: detect, get: get, lsvLimit: lsvLimit, isVerified: isVerified, lawLink: lawLink, dmvLink: dmvLink, search: search };
})();
if (typeof module !== 'undefined' && module.exports) module.exports = ST;
`;
fs.writeFileSync(path.join(__dirname, '..', 'states.js'), body);
console.log('wrote states.js', body.length, 'bytes,', out.length, 'states');
